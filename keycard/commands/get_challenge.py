from .. import constants
from ..card_interface import CardInterface
from ..exceptions import InvalidResponseError, InvalidStateError
from ..preconditions import require_selected
from ..secure_channel import SecureChannelVersion, channel_version


@require_selected
def get_challenge(card: CardInterface, length: int) -> bytes:
    '''
    Gets random bytes generated by the card.

    Applet 4.0 answers only inside the secure channel, also before INIT.
    Earlier applets that support the command answer with or without one;
    without a channel the command is sent in plain.

    Args:
        card: The card interface.
        length (int): Number of bytes, 1 to 255. The card limits it
            further: 245 bytes over Secure Channel V2, 221 over V1.

    Returns:
        bytes: The random bytes.

    Raises:
        ValueError: If the length does not fit in P1.
        InvalidStateError: If a Secure Channel V2 card has no open channel.
        InvalidResponseError: If the card returns a different length.
        APDUError: If the card returns a failure status word.
    '''
    if not 1 <= length <= 0xFF:
        raise ValueError('length must be between 1 and 255')

    if card.is_secure_channel_open:
        response = card.send_secure_apdu(
            ins=constants.INS_GET_CHALLENGE, p1=length)
    elif channel_version(card.version) == SecureChannelVersion.V2:
        raise InvalidStateError('Secure Channel must be satisfied.')
    else:
        response = card.send_apdu(
            ins=constants.INS_GET_CHALLENGE, p1=length)

    if len(response) != length:
        raise InvalidResponseError(
            f'Expected {length} random bytes, got {len(response)}')
    return response
